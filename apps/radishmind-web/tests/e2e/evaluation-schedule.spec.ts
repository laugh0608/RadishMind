import { test, expect, evaluation, button, evaluationLanguage, openEvaluation, createPlan, evaluationLayout } from "./evaluation-fixtures";
import { selectApplication } from "./workflow-fixtures";
import { installScheduleProjection } from "./evaluation-schedule-fixtures";

test.use({ applicationKind: "prompt_application" });
test.afterEach(async ({ page }) => { if (!page.isClosed()) await page.close(); });

test("evaluation schedule projections preserve cadence, confirmation, conflict, occurrence errors and refresh across languages", async ({ page, application }, info) => {
  const ui = evaluationLanguage(page, info), copy = ui.copy;
  const created = await createPlan(page, application.id, ui);
  const fixture = await installScheduleProjection(page, application.id, created.body.plan);
  await openEvaluation(page, "schedule");
  const panel = page.locator(".application-evaluation-schedule-owner");
  await expect(panel).toContainText(copy("No schedules exist", "没有日程"));
  const key = () => panel.getByRole("textbox", { name: copy("Actor-owned API key id", "操作者所属 API key 标识"), exact: true });
  const hour = () => panel.getByRole("spinbutton", { name: copy("Daily UTC hour", "每日 UTC 小时"), exact: true });
  const minute = () => panel.getByRole("spinbutton", { name: copy("Minute", "分钟"), exact: true });
  await key().fill("key_aaaaaaaaaaaaaaaa");
  await hour().fill("25");
  await button(panel, copy("Review create", "审查创建")).click();
  await ui.switch();
  await expect(panel).toContainText(copy("hour must be 00–23", "小时须为 00–23"));
  await expect(hour()).toHaveValue("25");
  await hour().fill("03"); await minute().fill("45");
  await button(panel, copy("Review create", "审查创建")).click();
  await ui.switch();
  await expect(panel.locator(".application-evaluation-confirmation")).toBeVisible();
  await expect(hour()).toHaveValue("03"); await expect(minute()).toHaveValue("45");
  const held = fixture.hold();
  try {
    await button(panel, copy("Confirm Create", "确认创建")).click();
    await held.arrived; await ui.switch();
    await expect(button(panel, copy("Confirm Create", "确认创建"))).toBeDisabled();
    held.release();
    await expect(panel.locator(".application-evaluation-operation")).toContainText(copy("completed at record v1", "记录版本 v1"));
  } finally { held.release(); }
  expect(fixture.mutations).toHaveLength(1);
  expect(fixture.mutations[0]).toMatchObject({ schedule: { rule: "daily_utc", hour: 3, minute: 45 }, plan_digest: created.body.version.plan_digest, quota_api_key_id: "key_aaaaaaaaaaaaaaaa" });
  await button(panel, copy("Activate", "激活")).click(); await ui.switch();
  await expect(panel.locator(".application-evaluation-confirmation")).toContainText(copy("revalidates current authority and quota", "重新验证当前权威与配额"));
  await button(panel, copy("Confirm Activate", "确认激活")).click();
  await expect(panel).toHaveAttribute("data-schedule-state", "active");
  await evaluationLayout(page, evaluation(page), info, "schedule-active");
  fixture.conflict();
  await button(panel, copy("Pause", "暂停")).click();
  await button(panel, copy("Confirm Pause", "确认暂停")).click();
  await expect(panel).toContainText(copy("Schedule version conflict", "日程版本冲突"));
  await ui.switch();
  await expect(hour()).toHaveValue("03");
  await expect(panel).not.toContainText("SERVER PRIVATE PROSE");
  await expect(button(panel, copy("Pause", "暂停"))).toBeDisabled();
  fixture.fail("");
  await button(panel, copy("Reload exact owner", "重新加载精确记录")).click();
  await expect(button(panel, copy("Pause", "暂停"))).toBeEnabled();
  await button(panel, copy("Pause", "暂停")).click();
  await button(panel, copy("Confirm Pause", "确认暂停")).click();
  await expect(panel).toHaveAttribute("data-schedule-state", "paused");
  await button(panel, copy("Review revision", "审查修订")).click();
  await ui.switch(); await button(panel, copy("Cancel", "取消")).click();
  await button(panel, copy("Resume", "恢复")).click();
  await button(panel, copy("Confirm Resume", "确认恢复")).click();
  await expect(panel).toHaveAttribute("data-schedule-state", "active");
  await openEvaluation(page, "occurrence");
  await expect(panel.getByRole("textbox", { name: "scheduled_for_utc", exact: true })).toHaveValue(fixture.time);
  fixture.fail("application_evaluation_schedule_not_found");
  await button(panel, copy("Read exact occurrence", "读取精确发生记录")).click();
  await expect(panel).toContainText(copy("exact Schedule or occurrence is unavailable", "精确日程或发生记录不可用"));
  await ui.switch();
  await expect(panel).not.toContainText("SERVER PRIVATE PROSE");
  fixture.fail("");
  await button(panel, copy("Read exact occurrence", "读取精确发生记录")).click();
  await expect(panel.locator(".application-evaluation-occurrence-result")).toContainText(copy("skipped", "已跳过"));
  await expect(panel).toContainText("application_evaluation_schedule_missed_window");
  await expect(panel).toContainText(copy("Missed window recorded without catch-up", "已记录错过的窗口，不补跑"));
  await ui.switch();
  await expect(panel.getByRole("textbox", { name: "scheduled_for_utc", exact: true })).toHaveValue(fixture.time);
  await evaluationLayout(page, evaluation(page), info, "occurrence-skipped");
  await openEvaluation(page, "schedule");
  await button(panel, copy("Review archive", "审查归档")).click();
  await ui.switch();
  await button(panel, copy("Confirm Archive", "确认归档")).click();
  await expect(panel).toHaveAttribute("data-schedule-state", "archived");
  const mutations = fixture.mutations.length;
  await page.reload(); await selectApplication(page, application); await openEvaluation(page, "schedule");
  await expect(panel).toHaveAttribute("data-schedule-state", "archived");
  expect(fixture.mutations).toHaveLength(mutations);
  expect(ui.requests.filter(value => /^POST .*evaluation-campaigns/.test(value))).toHaveLength(0);
});
