import { test, expect, evaluation, planOwner, button, evaluationLanguage, openEvaluation, evaluationSubmit, evaluationLayout } from "./evaluation-fixtures";
import { createDraft, saveDraft, draftField, selectApplication } from "./workflow-fixtures";
import { promotionRequest } from "./workflow-rag-promotion-fixtures";

test.use({ applicationKind: "workflow_copilot" });

test("Workflow evaluation keeps one invalid draft, adopts explicit authority and saves the visible fixtures", async ({ page, application }, info) => {
  test.setTimeout(150_000);
  const ui = evaluationLanguage(page, info), copy = ui.copy;
  await createDraft(page);
  await page.getByRole("button", { name: copy("New structured input draft", "新建结构化输入草案"), exact: true }).click();
  const draftId = await draftField(page, "Draft").innerText();
  const contract = page.locator(".workflow-contract-editor");
  for (const [index, name, type] of [[1, "attempts", "integer"], [2, "confirmed", "boolean"]] as const) {
    await button(contract, copy("Add field", "添加字段")).click();
    const field = contract.locator("fieldset").nth(index);
    await field.getByRole("textbox", { name: copy("Field name", "字段名称"), exact: true }).fill(name);
    await field.getByRole("textbox", { name: copy("Display label", "显示标签"), exact: true }).fill(name);
    await field.getByRole("combobox").selectOption(type);
    await field.getByRole("checkbox").check();
  }
  await saveDraft(page, 1);
  const definition = `evaluation_${application.id}`, candidate = `candidate_${application.id}`;
  await promotionRequest(page, application.id, "/v1/user-workspace/workflow-definition-candidates", ["workflow_definitions:write"], {
    candidate_id: candidate, definition_id: definition, draft_id: draftId, expected_draft_version: 1, expected_lifecycle_version: 1, execution_profile: "workflow_definition_executor_v2",
  });
  await promotionRequest(page, application.id, `/v1/user-workspace/workflow-definition-candidates/${candidate}/decisions`, ["workflow_definitions:review"], { expected_review_version: 0, decision: "approve", reason: "Synthetic evaluation reference" });
  const activationPath = `/v1/user-workspace/workflow-definitions/${definition}/activation-decisions`;
  await promotionRequest(page, application.id, activationPath, ["workflow_definitions:activate"], { expected_pointer_version: 0, decision: "activate", version: 1, reason: "Synthetic reference activation" });
  await openEvaluation(page, "plan");
  const panel = planOwner(page), reference = panel.locator(".workflow-evaluation-reference");
  await button(reference, copy("Read current reference", "读取当前引用")).click();
  await reference.getByRole("combobox").selectOption(definition);
  await button(reference, copy("Read current reference", "读取当前引用")).click();
  await expect(reference.locator("dl")).toContainText(definition);
  await button(reference, copy("Adopt reference and review fixtures", "采用引用并检查样本")).click();
  await panel.getByRole("textbox", { name: copy("Plan name", "计划名称"), exact: true }).fill("Workflow visible fixtures");
  const json = () => panel.getByRole("textbox", { name: copy("Ordered fixtures · 1–20 · advanced strict JSON", "有序夹具 · 1–20 项 · 高级严格 JSON"), exact: true });
  const items = [0, 1].map(index => ({ item_key: `sample_${index}`, name: `Sample ${index}`, expected_classification: "unchanged", workflow_definition: { inputs: { input_text: `Synthetic sample ${index}`, attempts: 2, confirmed: false } }, application_rag: null, prompt_application: null, agent_copilot: null }));
  await json().fill(JSON.stringify(items, null, 2));
  const attempts = panel.getByRole("textbox", { name: "attempts", exact: true });
  const review = () => button(panel, copy("Review create", "审查创建"));
  await expect(review()).toBeEnabled();
  await attempts.fill("invalid-int");
  await expect(review()).toBeDisabled();
  expect(JSON.parse(await json().inputValue())[0].workflow_definition.inputs.attempts).toBe("invalid-int");
  const sample = () => panel.getByRole("combobox", { name: copy("Fixture", "夹具"), exact: true });
  await sample().selectOption("1"); await expect(attempts).toHaveValue("2");
  await expect(review()).toBeDisabled();
  await sample().selectOption("0"); await expect(attempts).toHaveValue("invalid-int");
  await ui.switch(); await expect(attempts).toHaveValue("invalid-int");
  await attempts.fill("3");
  await button(panel.locator(".structured-runtime-boolean"), copy("Clear", "清除")).click();
  await expect(review()).toBeDisabled();
  await panel.getByRole("radio", { name: "false", exact: true }).check();
  const validJSON = await json().inputValue();
  const noRequired = JSON.parse(validJSON); delete noRequired[0].workflow_definition.inputs.input_text;
  await json().fill(JSON.stringify(noRequired)); await expect(review()).toBeDisabled();
  await json().fill("[{broken-json"); await expect(review()).toBeDisabled();
  await expect(panel.locator(".application-evaluation-structured-fixture.invalid")).toBeVisible();
  await json().fill(validJSON);
  await review().click();
  await expect(panel.locator(".application-evaluation-confirmation-values")).toContainText('"attempts": 3');
  await attempts.fill("4");
  await expect(panel.locator(".application-evaluation-confirmation")).toHaveCount(0);
  await expect(review()).toBeEnabled();
  // External pointer changes never silently rewrite the draft target or its samples.
  await promotionRequest(page, application.id, activationPath, ["workflow_definitions:activate"], { expected_pointer_version: 1, decision: "deactivate", version: 0, reason: "Synthetic pointer change" });
  await promotionRequest(page, application.id, activationPath, ["workflow_definitions:activate"], { expected_pointer_version: 2, decision: "activate", version: 1, reason: "Synthetic pointer refresh" });
  const target = () => panel.getByRole("textbox", { name: copy("Profile target · strict JSON", "档案目标 · 严格 JSON"), exact: true });
  const oldTarget = await target().inputValue();
  await button(reference, copy("Read current reference", "读取当前引用")).click();
  await expect(reference.locator("dl")).toContainText("v1 · 3");
  await expect(target()).toHaveValue(oldTarget); await expect(attempts).toHaveValue("4");
  const pattern = new RegExp(`/workflow-definitions/${definition}/activation\\?`);
  await page.route(pattern, route => route.fulfill({ status: 503, body: "Synthetic unavailable" }));
  await button(reference, copy("Read current reference", "读取当前引用")).click();
  await expect(reference.getByRole("alert")).toBeVisible();
  await expect(button(reference, copy("Adopt reference and review fixtures", "采用引用并检查样本"))).toBeDisabled();
  await expect(target()).toHaveValue(oldTarget); await expect(attempts).toHaveValue("4");
  await page.unroute(pattern);
  await button(reference, copy("Read current reference", "读取当前引用")).click();
  await expect(reference.locator("dl")).toContainText("v1 · 3");
  await button(reference, copy("Adopt reference and review fixtures", "采用引用并检查样本")).click();
  expect(JSON.parse(await target().inputValue()).workflow_definition.expected_pointer_version).toBe(3);
  await expect(attempts).toHaveValue("4");
  await page.evaluate(() => { window.location.hash = "application-evaluation-campaign"; });
  await expect(evaluation(page).getByRole("alertdialog")).toBeVisible();
  await button(evaluation(page), copy("Keep editing", "继续编辑")).click();
  await expect(attempts).toHaveValue("4");
  await page.locator(".product-nav").getByRole("link", { name: copy("Run history", "运行记录"), exact: true }).click();
  await expect(evaluation(page).getByRole("alertdialog")).toBeVisible();
  await button(evaluation(page), copy("Keep editing", "继续编辑")).click();
  await expect(attempts).toHaveValue("4");
  await attempts.focus(); await page.keyboard.press("Tab");
  await expect(panel.getByRole("radio", { name: "false", exact: true })).toBeFocused();
  await review().click();
  await evaluationLayout(page, panel, info, "workflow-plan-review");
  const saved = await evaluationSubmit(page, button(panel, copy("Confirm Create", "确认创建")), `/v1/user-workspace/applications/${application.id}/evaluation-plans`);
  expect(saved.body.failure_code).toBeNull();
  expect(saved.body.version.items[0].workflow_definition.inputs.attempts).toBe(4);
  expect(saved.body.version.target.workflow_definition.expected_pointer_version).toBe(3);
  expect(saved.request.postDataJSON().items).toEqual(saved.body.version.items);
  await expect(evaluation(page).locator(".application-evaluation-operation")).toContainText(saved.body.plan.plan_id);
  await attempts.fill("discard-me");
  await button(panel, copy("Load exact version", "加载精确版本")).click();
  await button(evaluation(page), copy("Discard and continue", "放弃并继续")).click();
  await expect(attempts).toHaveValue("4");
  await page.reload(); await selectApplication(page, application); await openEvaluation(page, "plan");
  await button(planOwner(page), copy("Load exact version", "加载精确版本")).click();
  await expect(planOwner(page).getByRole("textbox", { name: "attempts", exact: true })).toHaveValue("4");
});
